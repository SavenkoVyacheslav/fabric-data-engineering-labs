---------------------------------------------------------------
-- SELECT
---------------------------------------------------------------

SELECT
    title,
    author
FROM books;


---------------------------------------------------------------
-- DISTINCT
---------------------------------------------------------------

SELECT DISTINCT
    author
FROM books;


---------------------------------------------------------------
-- Column Alias
---------------------------------------------------------------

SELECT
    author AS book_author
FROM books;


---------------------------------------------------------------
-- CREATE VIEW
---------------------------------------------------------------

CREATE VIEW library_authors AS
SELECT DISTINCT
    author AS unique_author
FROM books;


---------------------------------------------------------------
-- LIMIT
---------------------------------------------------------------

SELECT
    *
FROM books
LIMIT 2;